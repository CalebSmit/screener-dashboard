@dataclass(frozen=True)
class Claim:
    """One sentence-template that states how a number is computed."""

    id: str
    surface: str
    #: What the sentence tells the reader, in plain English.
    asserts: str
    #: ``module:qualname`` - the code that makes it true.
    made_true_by: str
    #: ``tests/test_x.py::test_y`` entries that assert it.
    checked_by: tuple[str, ...]
    #: Regex that must be found in the surface's text. ``None`` for surfaces
    #: whose text is assembled per stock and checked by ``checked_by`` instead.
    detect: str | None = None
    #: Known limits of the claim - recorded so the next stage inherits them
    #: rather than rediscovering them.
    caveat: str = ""

    def resolve(self):
        """Import ``made_true_by`` and return the attribute, or raise."""
        module_name, _, qualname = self.made_true_by.partition(":")
        obj = importlib.import_module(module_name)
        for part in qualname.split("."):
            obj = getattr(obj, part)
        return obj


