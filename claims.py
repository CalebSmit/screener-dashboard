# Unlike CLAIMS, which enumerates listed surfaces, these are checked against
# every published artifact. Each one shipped to the live public site.

@dataclass(frozen=True)
class Forbidden:
    pattern: str
    why: str
    fixed: str = ""


FORBIDDEN: tuple[Forbidden, ...] = (
    Forbidden(
        pattern=r"composite of [\d.]+ is a percentile",
        why=("The drilldown's first sentence for all 502 stocks. Composite is "
             "cardinal; this told the stock ranked 1st that it scored above 74% "
             "of the universe."),
        fixed="2026-10-07 (T0a)",
    ),
    Forbidden(
        pattern=r"score of 95 means [\"']?better than 95%",
        why=("README and the generated methodology page's Step 5. Same error, "
             "stated as a general rule for reading any composite."),
        fixed="2026-10-07 (T0a)",
    ),
    Forbidden(
        pattern=r"raw composite is then converted to a cross-sectional percentile",
        why=("Step 5 of the generated methodology page - the sentence a student "
             "reads to learn what the headline number means."),
        fixed="2026-10-07 (T0a)",
    ),
    Forbidden(
        pattern=r"`Composite` is a percentile rank, not the weighted sum",
        why=("plan/investor-profiles.md told a future session to add a "
             "client-side percentile transform, which would have stopped the "
             "recompute reproducing the engine's own published numbers."),
        fixed="2026-10-07 (T0a)",
    ),
)


# ---------------------------------------------------------------------------
# Helpers used by the tests and by scripts/check_published_claims.py
# ---------------------------------------------------------------------------

def claims_for(surface: str) -> tuple[Claim, ...]:
    return tuple(c for c in CLAIMS if c.surface == surface)


def claim(claim_id: str) -> Claim:
    for c in CLAIMS:
        if c.id == claim_id:
            return c
    raise KeyError(claim_id)


def registered_builders() -> set[str]:
    """``{"_sentence_rank", ...}`` - the stock_summary functions with a claim."""
    out = set()
    for c in CLAIMS:
        if c.surface != SUMMARY:
            continue
        _, _, qualname = c.made_true_by.partition(":")
        out.add(qualname)
    return out


def forbidden_hits(text: str) -> list[Forbidden]:
    """Every FORBIDDEN pattern present in ``text``."""
    import re
    return [f for f in FORBIDDEN if re.search(f.pattern, text)]


def open_caveats() -> tuple[Claim, ...]:
    """Claims carrying a known, recorded limitation - the T0b work list."""
    return tuple(c for c in CLAIMS if c.caveat)
