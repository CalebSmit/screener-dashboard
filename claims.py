"""The claims register: every sentence on the site that says how a number is
computed, and the code that makes it true.

Why this exists
---------------
On 2026-10-06 the drilldown's **first sentence**, shown for all 502 stocks, read:

    Ranks 1st of 502. Its composite of 73.8 is a percentile: it scores above
    74% of the universe.

For the stock ranked **1st of 502**. ``Composite`` has been the *cardinal*
weighted average of the category scores since Phase 13 (F1) and the percentile
is the separate ``Composite_Pct`` column, so the claim was wrong by a median of
**19.6 percentage points** across the universe, by more than 10 points for
**74.9%** of stocks, and by **31.2** at worst
(``research/measurements/2026-10-06-rank-sentence-claim.py``, re-measured
2026-10-07).

It had been live for months, and the reason is the part worth engineering
against: **there was a test asserting it.**
``tests/test_stock_summary.py::test_composite_is_described_as_a_universe_percentile``
asserted the sentence said "above 75% of the universe" and cited
``SCREENER_OVERVIEW.md`` as its authority - while the *same* methodology page's
Limitation 8 said the opposite. Correcting the sentence would have looked like a
regression. A claim is only ever as good as the thing that checks it, and a
check pointed at the wrong authority is worse than none.

``scripts/check_published_claims.py`` could not catch it either, because it
tests "specific claims people thought to write down". The gap was structural:
nothing enumerated the *set* of computational claims the site makes, so nothing
could notice one of them was unchecked.

What this module is
-------------------
A single table. Each :class:`Claim` names

* the **surface** the sentence appears on,
* what it **asserts** about how a number is computed, in plain English,
* the code that **makes it true** (``module:qualname``), and
* the test that **checks it**.

``tests/test_claims_register.py`` then enforces the properties that make it a
tripwire rather than documentation:

1. every sentence builder in ``stock_summary.py`` is registered - so adding a
   ``_sentence_*`` function fails the suite until its claim is written down;
2. every ``made_true_by`` resolves to a real attribute of a real module;
3. every ``checked_by`` names a test function that actually exists;
4. every ``detect`` pattern still matches its surface - so silently rewording a
   registered sentence makes the register stale *loudly*; and
5. no :data:`FORBIDDEN` pattern appears in anything published - the direct
   regression guard on the four false statements fixed on 2026-10-07.

Scope, deliberately
-------------------
Claim-shaped vocabulary ("percentile", "weighted", "median", "average",
"discount") appears in hundreds of sentences across a 55 KB methodology page.
Requiring a register entry for every one of them would produce a register
nobody maintains. So the enumerated surfaces are the ones that **state the
arithmetic of a published number**: the per-stock summary sentences, and the
numbered Steps plus the composite/coverage rules on the generated methodology
page. ``FORBIDDEN`` is the complement and applies everywhere.

Stage T0a of ``plan/calculation-transparency.md``. T1 extends this with the
per-metric lineage registry; the two are meant to converge.
"""

