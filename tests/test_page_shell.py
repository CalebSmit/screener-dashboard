def _png_size(path: Path) -> tuple[int, int]:
    head = path.read_bytes()[:24]
    assert head[:8] == b"\x89PNG\r\n\x1a\n", f"{path.name} is not a PNG"
    return struct.unpack(">II", head[16:24])


def test_the_home_screen_files_exist_and_say_what_they_are():
    head = _html()[:_html().index("</head>")]
    assert '<link rel="apple-touch-icon" href="icon-180.png">' in head
    assert '<link rel="manifest" href="manifest.webmanifest">' in head
    assert _png_size(ROOT / "icon-180.png") == (180, 180)
    man = json.loads((ROOT / "manifest.webmanifest").read_text(encoding="utf-8"))
    assert man["start_url"] == "./" and man["scope"] == "./" and man["display"] == "standalone"
    assert man["background_color"] == man["theme_color"] == "#0d0d0d"
    assert re.search(r'<meta name="theme-color" content="#0d0d0d">', head)
    sizes = {}
    for icon in man["icons"]:
        w, h = _png_size(ROOT / icon["src"])
        assert icon["sizes"] == f"{w}x{h}", icon
        sizes.setdefault(icon["purpose"], set()).add(w)
    assert {192, 512} <= sizes["any"] and 512 in sizes["maskable"]
    # no service worker: a cached payload that outlived its run would be worse than none
    assert "serviceWorker" not in _html()


