def test_the_run_time_is_the_same_instant_in_every_readers_zone(browser, server, zone):
    """kpis.run_timestamp is the run machine's US Central wall time with no offset. Read in the reader's
    own zone, a 02:00 Central run showed as "2:00 AM GMT" in London; it is 07:00 or 08:00 there."""
    from zoneinfo import ZoneInfo
    run = datetime.fromisoformat(_run_timestamp()).replace(tzinfo=ZoneInfo("America/Chicago"))
    local = run.astimezone(ZoneInfo(zone))
    want = local.strftime("%b ") + str(local.day) + local.strftime(", %Y, ") + local.strftime("%I:%M %p").lstrip("0")
    ctx = browser.new_context(viewport={"width": 1280, "height": 900}, timezone_id=zone)
    ctx.route(OFFSITE, lambda r: r.abort())
    page, errors = _page(ctx)
    try:
        page.goto(server + "index.html", wait_until="load")
        page.wait_for_function(READY, timeout=30000)
        foot = page.inner_text("#gen-time").replace(" ", " ")
        eyebrow = page.inner_text("#hero-eyebrow").replace(" ", " ")
        assert foot.startswith(want), (zone, foot, want)
        assert want.upper() in eyebrow.upper(), (zone, eyebrow, want)
        assert errors == []
    finally:
        ctx.close()
