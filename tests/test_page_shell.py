OFFSITE = re.compile(r"^https?://(?!127\.0\.0\.1[:/])")


def _context(browser, width=1280, height=900, touch=False):
    opts = {"viewport": {"width": width, "height": height}}
    if touch:
        opts.update(is_mobile=True, has_touch=True)
    ctx = browser.new_context(**opts)
    ctx.route(OFFSITE, lambda r: r.abort())          # never the network, fonts included
    return ctx


def _page(ctx):
    page = ctx.new_page()
    errors: list[str] = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    return page, errors


def _visible_skeletons(page) -> int:
    return page.evaluate("[...document.querySelectorAll('.sk')].filter(e => e.offsetParent !== null).length")


@needs_browser
@pytest.mark.parametrize("width", [375, 1280])
def test_a_payload_that_never_arrives_says_so_and_offers_a_reload(browser, server, width):
    ctx = _context(browser, width=width, height=812 if width < 700 else 900, touch=width < 700)
    ctx.route("**/dashboard_data.js*", lambda r: r.abort())
    page, errors = _page(ctx)
    try:
        page.goto(server + "index.html", wait_until="load")
        page.wait_for_selector("#load-fail", state="visible", timeout=WAIT)
        assert page.get_attribute("#load-fail", "data-kind") == "network"
        assert page.get_attribute("#load-fail", "role") == "alert"
        text = page.inner_text("#load-fail")
        assert "The rankings did not load" in text and "could not be downloaded" in text
        # the developer's note it replaced is gone
        assert "redeploy" not in page.inner_text("body") and "Ctrl+F5" not in page.inner_text("body")
        btn = page.get_by_role("button", name="Reload the page")
        assert btn.is_visible()
        # nothing pulses for good, no empty frame, no link into a section that is not drawn
        assert _visible_skeletons(page) == 0
        for sel in ("#kpi-row", "#dist", "#sec-top5", "#sec-universe", ".header-nav", "#guide"):
            assert not page.is_visible(sel), sel
        assert page.get_attribute("#kpi-row", "aria-busy") is None
        assert page.is_visible(".hero-title")
        assert not page.is_visible("#load-wait")
        assert errors == []
        # and the reload does what it says: with the file reachable again, the rankings draw
        ctx.unroute("**/dashboard_data.js*")
        btn.click()
        page.wait_for_function(READY, timeout=30000)
        assert not page.is_visible("#load-fail")
    finally:
        ctx.close()


