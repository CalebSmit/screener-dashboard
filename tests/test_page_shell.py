def _at(page_server, browser, now_iso: str):
    ctx = _context(browser)
    page, errors = _page(ctx)
    page.clock.set_fixed_time(datetime.fromisoformat(now_iso))
    page.goto(page_server + "index.html", wait_until="load")
    page.wait_for_function(READY, timeout=30000)
    return ctx, page, errors


@needs_browser
def test_staleness_counts_weekday_runs_and_never_trading_days(browser, server):
    """The data loop publishes every weekday, NYSE holidays included (the 2026-09-07 Labor Day run
    published like any other), so the count is of weekdays; a weekday's run is overdue from 14:00 UTC."""
    ctx, page, errors = _at(server, browser, "2026-10-27T15:00:00+00:00")
    try:
        cases = [
            # (run timestamp, reader's clock UTC, overdue weekday runs)
            ("2026-10-27T02:00:05", "2026-10-27T15:00:00Z", 0),
            ("2026-10-27T02:00:05", "2026-10-28T13:59:00Z", 0),   # Wednesday's run not yet due
            ("2026-10-27T02:00:05", "2026-10-28T14:00:00Z", 1),
            ("2026-10-27T02:00:05", "2026-10-29T14:00:00Z", 2),
            ("2026-10-23T02:00:05", "2026-10-26T15:00:00Z", 1),   # Friday's run read on Monday: the weekend is not counted
            ("2026-10-23T02:00:05", "2026-10-25T23:00:00Z", 0),
            ("2026-09-04T02:12:00", "2026-09-08T15:00:00Z", 2),   # over Labor Day: the holiday run was due too
            ("not a date", "2026-10-29T14:00:00Z", None),
        ]
        for run, now, want in cases:
            got = page.evaluate("([r, n]) => { const s = runStaleness(r, Date.parse(n)); return s ? s.missed : null; }", [run, now])
            assert got == want, (run, now, got, want)
            if want is not None:
                stale = page.evaluate("([r, n]) => runStaleness(r, Date.parse(n)).stale", [run, now])
                assert stale is (want >= 2)
        assert errors == []
    finally:
        ctx.close()


@needs_browser
def test_a_page_two_weekday_runs_behind_says_so_and_a_current_one_says_nothing(browser, server):
    run = _run_timestamp()
    run_day = datetime.fromisoformat(run[:10]).replace(tzinfo=timezone.utc)
    # the reader's clock: the same afternoon (nothing to say), then after two more weekdays' runs were due
    same_day = run_day.replace(hour=15)
    ctx, page, errors = _at(server, browser, same_day.isoformat())
    try:
        assert page.evaluate("document.getElementById('stale-note')") is None
        assert page.is_hidden("#page-notices") or page.inner_text("#page-notices").strip() == ""
    finally:
        ctx.close()
    d = run_day
    weekdays = 0
    while weekdays < 2:
        d = d.fromordinal(d.toordinal() + 1).replace(tzinfo=timezone.utc)
        if d.weekday() < 5:
            weekdays += 1
    later = d.replace(hour=15)
    ctx, page, errors = _at(server, browser, later.isoformat())
    try:
        page.wait_for_selector("#stale-note", state="visible", timeout=WAIT)
        text = page.inner_text("#stale-note")
        want_day = run_day.strftime("%A, %b ") + str(run_day.day)
        assert f"These figures are from the run of {want_day}." in text, text
        assert "2 weekday runs since then have not" in text
        assert page.evaluate("getComputedStyle(document.getElementById('stale-note')).borderLeftColor") == "rgb(250, 178, 25)"
        import stock_summary
        assert stock_summary.advice_terms_in(text) == []
        assert errors == []
    finally:
        ctx.close()


